// Build step: 4K sources -> responsive AVIF/WebP + typed slide data.
//   node scripts/optimize.mjs
// Inputs:  ../ref_image_4k (backgrounds), assets-src/<page>/<layer>.{png,json} (from tools/build_layers.py)
// Outputs: public/img/**, src/slides.generated.ts
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ref4k = join(root, '..', 'ref_image_4k')
const manifest = JSON.parse(readFileSync(join(root, 'tools', 'layers.json'), 'utf8'))
const BG_WIDTHS = [3840, 2560, 1920, 1280]
const out = (...p) => join(root, 'public', 'img', ...p)
for (const d of ['bg', 'layers']) mkdirSync(out(d), { recursive: true })

const avif = { quality: 72, effort: 4, chromaSubsampling: '4:4:4' }
const webp = { quality: 90, effort: 5, smartSubsample: true, alphaQuality: 100 }

async function emit(input, base, width, height) {
  const img = () => sharp(input).resize({ width, height, kernel: 'lanczos3' })
  await Promise.all([img().avif(avif).toFile(`${base}.avif`), img().webp(webp).toFile(`${base}.webp`)])
}

const slides = []
for (const [pid, cfg] of Object.entries(manifest)) {
  const [bgPage, bgName] = cfg.bg ?? cfg.base
  const bgSrc = join(ref4k, bgPage, bgName)
  const meta = await sharp(bgSrc).metadata()
  console.log(pid, 'bg', meta.width, 'x', meta.height)

  for (const w of BG_WIDTHS.filter((w) => w <= meta.width)) {
    await emit(bgSrc, out('bg', `${pid}-${w}`), w)
  }
  const lqip = await sharp(bgSrc).resize(24).blur(1).webp({ quality: 60 }).toBuffer()

  const layers = []
  for (const [, lid] of cfg.layers) {
    const png = join(root, 'assets-src', pid, `${lid}.png`)
    if (!existsSync(png)) continue
    const box = JSON.parse(readFileSync(join(root, 'assets-src', pid, `${lid}.json`), 'utf8'))
    const m = await sharp(png).metadata()
    const half = Math.round(m.width / 2)
    await emit(png, out('layers', `${pid}-${lid}`), m.width)
    await emit(png, out('layers', `${pid}-${lid}-half`), half)
    layers.push({ id: lid, px: m.width, ...box })
  }
  slides.push({
    id: pid,
    bg: { widths: BG_WIDTHS.filter((w) => w <= meta.width), ratio: +(meta.width / meta.height).toFixed(5), lqip: `data:image/webp;base64,${lqip.toString('base64')}` },
    layers,
  })
}

const ts = `// GENERATED by scripts/optimize.mjs - do not edit.
export interface GeneratedLayer { id: string; px: number; x: number; y: number; w: number; h: number }
export interface GeneratedSlide {
  id: string
  bg: { widths: number[]; ratio: number; lqip: string }
  layers: GeneratedLayer[]
}
export const generated: GeneratedSlide[] = ${JSON.stringify(slides, null, 1)}
`
writeFileSync(join(root, 'src', 'slides.generated.ts'), ts)
console.log('done', slides.length, 'slides')
